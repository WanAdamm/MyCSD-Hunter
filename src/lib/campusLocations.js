// Bilinear transformation mapping map percentages (x, y) to real-world GPS coordinates
// Calibrated against ground-truth surveyed USM campus landmarks
export const toCoordinates = (x, y) => {
  const lat = 5.36464284 - 0.000007 * x - 0.00015768 * y + 0.0000002036 * x * y;
  const lng = 100.29023542 + 0.00020899 * x - 0.0000445 * y + 0.0000006748 * x * y;
  return {
    lat: Number(lat.toFixed(6)),
    lng: Number(lng.toFixed(6)),
  };
};

export const getGoogleMapsUrl = (place) => {
  if (!place || typeof place.lat !== 'number' || typeof place.lng !== 'number') return '#';
  return `https://www.google.com/maps/search/?api=1&query=${place.lat},${place.lng}`;
};

export const getPlaceName = (place, lang = 'ms') => {
  if (!place) return '';
  return lang === 'ms' && place.nameMs ? place.nameMs : place.name;
};

export const getZoneName = (zoneCode, lang = 'ms') => {
  const zone = campusZones[zoneCode];
  if (!zone) return '';
  return lang === 'ms' && zone.nameMs ? zone.nameMs : zone.name;
};

